-- 002_auth.sql — 인증. **이 앱에 「사용자」라는 개념이 처음 생기는 파일이다.**
--
-- 지금까지 서버가 다룬 것은 익명 의견 한 종류뿐이었다(001). 여기서부터
-- "이 요청이 누구인지"를 서버가 판단하게 된다. 왜 이 모양인지는
-- ROADMAP.md의 «🔐 인증 설계 확정 (2026-08-25)» 절에 근거까지 적어뒀다.
--
-- 실행법: Neon 콘솔 → SQL Editor → 붙여넣고 Run.
-- ⚠️ 마이그레이션 도구는 아직 안 쓴다(001과 같다). 파일 이름의 번호가 순서고 실행은 손으로 한다.
--
-- ⚠️ **이 파일은 인증까지만 만든다.** 내 데이터(myChannels·watched·laterPool·playlistId)를
--    옮기는 테이블은 003에서 만든다. 인증이 먼저 서야 그것들이 누구 것인지 말할 수 있다.

-- ────────────────────────── 사용자 ──────────────────────────
create table if not exists app_user (
  id          bigserial   primary key,
  -- 구글 OAuth의 sub. 계정마다 고정이고 재사용되지 않는다.
  -- ⛔ 이메일을 키로 쓰지 않는다 — 사람은 이메일을 바꾼다. sub는 안 바뀐다.
  google_sub  text        not null unique,
  created_at  timestamptz not null default now()
);

-- ⛔ **refresh_token 칸을 일부러 만들지 않는다** (2026-08-25 결정).
--  구글은 code 교환 때 refresh 토큰을 준다 — GIS의 initCodeClient에는 그걸 끄는
--  파라미터(access_type)가 아예 없어서 **안 받을 방법이 없다.** 그래서 받고 버린다.
--  칸을 만드는 순간 시작되는 것: 만료 없다시피 한 상시 접근 권한을 내 DB에 보관하는 일 +
--  암호화 결정 + 권한 철회 시 삭제 로직 + 갱신 실패 경로.
--  그걸로 사는 것은 「1시간마다 로그인 버튼」이 「7일마다」가 되는 것뿐이다
--  (테스트 모드 프로젝트의 refresh 토큰은 7일 만료다 — 90-gotchas 15).
--  🚦 신호등: 사용자가 **앱을 안 열고 있는 동안** 구글을 불러야 할 때(알림·자동 동기화).

-- ────────────────────────── 세션 ──────────────────────────
-- ⭐ **내 서버가 발급하는 유일한 자격증명이다.** 지금까지 이 앱의 자격증명은 전부
--  구글 것을 받아 쓰는 것이었다(액세스 토큰). 여기서 처음으로 내가 발급한다.
--
-- 왜 필요한가: sub를 알아내는 것은 **로그인 순간 한 번**이다. 그 뒤 요청마다
--  "이게 누구지"를 답할 것이 따로 있어야 하는데, 매번 구글에 물으면 왕복이 붙고
--  구글이 아플 때 내 앱도 같이 죽는다.
--
-- ⭐ 왜 무상태 JWT가 아니라 행인가: **로그아웃**이다. JWT는 한 번 발급하면 못 거둔다
--  (블랙리스트를 따로 만들어야 하고, 그 블랙리스트가 결국 이 테이블이 된다).
--  행은 지우면 그 순간 끝이고, DB는 이미 있다.
create table if not exists session (
  -- ⛔ **쿠키에 담기는 값을 그대로 저장하지 않는다. sha256만 저장한다.**
  --  이 테이블이 유출되면 원본을 저장한 경우 **모든 세션을 그대로 훔쳐 쓸 수 있다**
  --  (세션 값은 그 자체가 곧 신분증이라 비밀번호와 같은 성질이다).
  --  해시를 두면 유출돼도 되돌릴 수 없다. 확인은 「받은 값을 해시해서 대조」로 똑같이 된다.
  --  ⭐ 001에서 IP를 sha256으로 둔 것과 같은 판단이다 — 세는 데(대조하는 데) 충분하면
  --     원본을 갖지 않는다. 다만 여기엔 소금이 필요 없다: IP는 후보가 43억이라 되돌릴 수
  --     있었지만, 세션 값은 우리가 만드는 256비트 난수라 애초에 뒤집을 수 없다.
  token_hash  text        primary key,

  user_id     bigint      not null references app_user(id) on delete cascade,
  created_at  timestamptz not null default now(),

  -- 슬라이딩 만료의 기준. ⚠️ **요청마다 갱신하지 않는다** — 읽기 한 번에 쓰기 한 번이
  --  따라붙어 모든 API가 두 배로 비싸진다. 마지막 갱신에서 하루 넘게 지났을 때만 민다.
  seen_at     timestamptz not null default now(),

  expires_at  timestamptz not null
);

-- 만료된 세션을 지우는 배치가 **없다**(크론을 안 들인다). 대신 둘로 버틴다:
--  ① 조회할 때 만료된 것이면 그 자리에서 지운다 (게으른 청소)
--  ② 가끔 손으로 `delete from session where expires_at < now()`
-- 🚦 크론 신호등: 이 테이블이 눈에 띄게 커질 때. 5명 규모에선 올 일이 없다.
create index if not exists session_expiry_idx on session (expires_at);

-- 한 사람의 세션을 전부 끊는 질의(= 모든 기기에서 로그아웃)가 이 인덱스를 탄다.
-- 지금 화면엔 그 버튼이 없지만, 계정 삭제·권한 철회 때 서버가 쓰게 된다.
create index if not exists session_user_idx on session (user_id);
